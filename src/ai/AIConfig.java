package ai;
public class AIConfig{
	private String apiKey;
    	public AIConfig() {
    	}
    	public AIConfig(String apiKey) {
        	this.apiKey = apiKey;
    	}
    	public String getApiKey() {
        	return apiKey;
    	}
    	public void setApiKey(String apiKey) {
        	this.apiKey = apiKey;
    	}
}
